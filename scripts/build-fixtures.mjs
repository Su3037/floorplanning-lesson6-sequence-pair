#!/usr/bin/env node
// fixtures/sequence-pair.json is the single source of the examples. This copies it to the places that read it:
// the browser (site/engines/fixtures.js, an ES module) and the Python pack (python/m06-sequence-pair/fixtures/).
import fs from 'node:fs';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = fs.readFileSync(path.join(ROOT, 'fixtures/sequence-pair.json'), 'utf8');
JSON.parse(src);
fs.writeFileSync(path.join(ROOT, 'site/engines/fixtures.js'), `// Generated by scripts/build-fixtures.mjs from fixtures/sequence-pair.json. Do not edit.\nexport const DATA = ${src.trim()};\n`);
fs.mkdirSync(path.join(ROOT, 'python/m06-sequence-pair/fixtures'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'python/m06-sequence-pair/fixtures/sequence-pair.json'), src);
console.log('fixtures → site/engines/fixtures.js, python/m06-sequence-pair/fixtures/');
